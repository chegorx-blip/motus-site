"""
Профиль владельца бота — единственное место, где описано, кто такой Che.

Идея: вместо того чтобы в каждом новом адаптере (почта, запчасти, финансы)
заново объяснять Claude, кто пользователь и как с ним говорить, все system
prompt'ы подключают отсюда готовый кусок текста через get_user_context().

Это НЕ отдельная "личность"/полноценный чат-ассистент — бот, как и раньше,
делает узкие разовые вызовы (см. classifier.py). Этот файл только даёт общий
фон, чтобы разные функции не расходились в тоне и не путали факты о владельце.

Источник правды — MEMORY.md из папки CLAUDE_MEMORY_DIR (та же папка, синкается
через Google Drive, см. adapters/memory_client.py). Ничего не хардкодим здесь —
если факт о пользователе изменился, его достаточно поправить в самой памяти
Claude Code, этот файл подхватит изменение сам при следующем вызове, без
редактирования кода бота.
"""

from pathlib import Path

from config import CLAUDE_MEMORY_DIR

_INDEX_FILENAME = "MEMORY.md"

# Ограничение на длину контекста, который уходит в каждый вызов Claude — MEMORY.md
# будет расти со временем, и без потолка каждая классификация со временем станет
# дороже и медленнее. 6000 символов — с запасом покрывает текущий файл (~2000
# символов), оставляя место на рост на годы вперёд, не раздувая при этом каждый
# отдельный вызов.
_MAX_CHARS = 6000

_FALLBACK_CONTEXT = """\
Владельца бота зовут Че (Che). Он живёт на Кипре.
(Не удалось прочитать полную память — см. лог; отвечай осторожнее с фактами \
о пользователе, при сомнении лучше уточнить, чем предполагать.)
"""

_INSTRUCTIONS = """\

КАК ОТВЕЧАТЬ:
- Коротко и по-русски (весь текст, независимо от исходного языка сообщения).
- Простым языком, без лишнего технического жаргона — если термин необходим, \
поясни его на ходу в двух словах.
- Прямо и по делу: если что-то непонятно или неоднозначно — лучше спросить \
коротким уточнением, чем гадать и придумывать детали.
- Не путай статус вещей: "куплено/используется" vs "рассматривается/в \
исследовании" vs "было решено отказаться" — если не уверен, уточни, а не \
предполагай.
"""


def get_user_context() -> str:
    """
    Возвращает блок текста с профилем владельца для вставки в system prompt:
    краткий индекс памяти Claude Code (MEMORY.md) + фиксированные инструкции
    по тону ответа. При любой ошибке чтения — короткий безопасный fallback,
    чтобы бот не падал целиком из-за недоступности файла памяти.
    """
    try:
        index_path = Path(CLAUDE_MEMORY_DIR) / _INDEX_FILENAME
        memory_index = index_path.read_text(encoding="utf-8").strip()
        if len(memory_index) > _MAX_CHARS:
            memory_index = memory_index[:_MAX_CHARS] + "\n… (обрезано по длине)"
        return (
            "О ПОЛЬЗОВАТЕЛЕ (кратко, из его памяти Claude Code):\n"
            f"{memory_index}\n"
            f"{_INSTRUCTIONS}"
        )
    except OSError:
        return _FALLBACK_CONTEXT + _INSTRUCTIONS
