"""
Классификатор смысла входящего сообщения.

Задача: посмотреть на распознанный текст (голос → текст уже случился до этого
шага) и решить, что пользователь хочет — создать или отменить событие в
календаре, записать мысль, разобраться с почтой или найти запчасть.
handlers/voice.py решает, какой обработчик вызвать, опираясь на результат отсюда.

Пока реализованы обработчики для "event", "cancel_event" и "thought" (см. handlers/) —
для mail/parts_search классификатор уже умеет их распознавать, но обработчик
пока отвечает "это ещё не готово" вместо реального действия. Это нормально —
достраиваем по одной функции за раз на уже работающем фундаменте.
"""

from adapters.claude_client import ask_structured

_SYSTEM_PROMPT = """\
Ты — классификатор сообщений личного помощника. Пользователь присылает голосовые \
сообщения, которые превращаются в текст. Твоя задача — определить, что это за \
сообщение, и вытащить из него полезные детали.

Типы сообщений:
- "event": напоминание или НОВОЕ событие для календаря (встреча, дело, звонок — что-то \
привязанное ко времени). Пример: "в понедельник в 9 позвонить в банк".
- "cancel_event": просьба отменить/удалить/перенести УЖЕ существующее событие. \
Пример: "отмени встречу с врачом", "убери напоминание про справки". Если пользователь \
ссылается на что-то расплывчато ("отмени это", "убери то, что выше") без названия — \
всё равно верни этот тип, но search_query оставь пустым, дальше решим отдельно.
- "thought": мысль, идея, заметка, что-то на будущее без конкретной привязки ко \
времени. Пример: "надо бы проверить шины перед зимой".
- "mail": просьба, связанная с почтой — проверить, ответить, что-то по письму.
- "parts_search": просьба найти автозапчасть (название или номер детали, диски, \
шины и т.п.).
- "unclear": не подходит ни под один тип, или сообщение слишком расплывчатое.

Для типа "event" дополнительно определи:
- title: короткое, ёмкое название события (не дословно то, что сказал пользователь — \
сократи до сути)
- date_hint: как пользователь описал дату/время, своими словами, как есть \
("в понедельник в 9", "завтра вечером") — календарным вычислением даты займётся \
другой шаг, здесь просто зафиксируй, что было сказано.

Для типа "cancel_event" дополнительно определи:
- search_query: ключевые слова для поиска события в календаре (например "врач", \
"справки") — только если пользователь назвал хоть что-то конкретное, иначе пусто.

Для типа "thought" дополнительно определи:
- is_explicit_save: true, ТОЛЬКО если пользователь прямо просит запомнить это \
насовсем — явные слова вроде "запомни это", "запиши это в память", "занеси в память", \
"запуш это"/"запушь это"/"запушено" (любая форма слова "запушить" — это отдельная \
команда пользователя сохранить насовсем), "сохрани навсегда". Обычная мысль вслух \
без такой явной просьбы — false. Это важное различие: true означает мысль сразу и \
бесповоротно попадёт в постоянную память, false — просто ляжет в черновой список на \
будущий разбор. Если сомневаешься — false.

Для остальных типов достаточно summary — короткое изложение сути одним предложением.
"""

_SCHEMA = {
    "type": "object",
    "properties": {
        "type": {
            "type": "string",
            "enum": ["event", "cancel_event", "thought", "mail", "parts_search", "unclear"],
        },
        "title": {"type": "string"},
        "date_hint": {"type": "string"},
        "search_query": {"type": "string"},
        "is_explicit_save": {"type": "boolean"},
        "summary": {"type": "string"},
    },
    "required": [
        "type",
        "title",
        "date_hint",
        "search_query",
        "is_explicit_save",
        "summary",
    ],
    "additionalProperties": False,
}


def classify(text: str) -> dict:
    """
    Возвращает словарь вида:
    {"type": "event", "title": "Позвонить в банк", "date_hint": "в понедельник в 9",
     "summary": "..."}
    Поля title/date_hint пустые строки, если не тип "event".
    """
    return ask_structured(_SYSTEM_PROMPT, text, _SCHEMA)
